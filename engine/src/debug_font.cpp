int DebugFont::cell_for(char c) {
    unsigned char u = static_cast<unsigned char>(c);
    if (u >= 'a' && u <= 'z') u = static_cast<unsigned char>(u - 'a' + 'A');
    if (u == '`') u = '\'';
    if (u == '{') u = '(';
    if (u == '}') u = ')';
    if (u == '|') u = '!';
    if (u == '~') u = '-';
    if (u < 32 || u > 95) u = 32;
    return u - 32;
}

std::vector<u8> DebugFont::build_atlas() {
    std::vector<u8> rgba(static_cast<usize>(kAtlasW) * kAtlasH * 4, 0);
    for (int glyph = 0; glyph < 64; ++glyph) {
        const int cx = (glyph % kColumns) * kCellW;
        const int cy = (glyph / kColumns) * kCellH;
        for (int row = 0; row < 7; ++row) {
            for (int col = 0; col < 5; ++col) {
                if (kGlyphs[glyph][row][col] != '#') continue;
                u8* p = &rgba[(static_cast<usize>(cy + row) * kAtlasW + cx + col) * 4];
                p[0] = p[1] = p[2] = p[3] = 255;
            }
        }
    }
    return rgba;
}

